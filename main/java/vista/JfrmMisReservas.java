    /** Documento escrito por el pasajero (sin espacios sobrantes). */
    public String getDocumento() {
        return txtDocumento.getText().trim();
    }

    /** Código de reserva escrito por el pasajero (sin espacios sobrantes). */
    public String getCodigo() {
        return txtCodigo.getText().trim();
    }

    /** Muestra el texto con los detalles de la reserva. */
    public void mostrarDetalles(String texto) {
        txtDetalles.setText(texto);
    }

    /** Habilita o deshabilita el botón "Cancelar reserva". */
    public void setCancelarHabilitado(boolean habilitado) {
        btnCancelar.setEnabled(habilitado);
    }

    /** Vacía los campos y deja la pantalla como al inicio. */
    public void limpiarCampos() {
        txtDocumento.setText("");
        txtCodigo.setText("");
        txtDetalles.setText(
                "Ingresa tu documento y el código de reserva para consultar los detalles.");
        btnCancelar.setEnabled(false);
    }

